package com.studentmgmt;

import java.sql.Timestamp;

/**
 * Student - Model / Entity Class (POJO)
 *
 * Maps directly to the 'students' table in MySQL.
 * Represents student personal and academic profile data.
 *
 * Viva Points:
 * 1. POJO (Plain Old Java Object): Follows encapsulation with private fields and public getters/setters.
 * 2. Model in MVC: Holds the state of an individual student record.
 */
public class Student {
    private int id;
    private String rollNumber;
    private String name;
    private String email;
    private String phone;
    private String department;
    private int year;
    private String address;
    private Timestamp createdAt;
    private Timestamp updatedAt;

    // Default constructor
    public Student() {
    }

    // Constructor for creating a new student (ID and timestamps auto-generated by MySQL)
    public Student(String rollNumber, String name, String email, String phone,
                   String department, int year, String address) {
        this.rollNumber = rollNumber;
        this.name = name;
        this.email = email;
        this.phone = phone;
        this.department = department;
        this.year = year;
        this.address = address;
    }

    // Full constructor when reading from database
    public Student(int id, String rollNumber, String name, String email, String phone,
                   String department, int year, String address, Timestamp createdAt, Timestamp updatedAt) {
        this.id = id;
        this.rollNumber = rollNumber;
        this.name = name;
        this.email = email;
        this.phone = phone;
        this.department = department;
        this.year = year;
        this.address = address;
        this.createdAt = createdAt;
        this.updatedAt = updatedAt;
    }

    // --- Getters and Setters ---

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getRollNumber() {
        return rollNumber;
    }

    public void setRollNumber(String rollNumber) {
        this.rollNumber = rollNumber;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPhone() {
        return phone;
    }

    public void setPhone(String phone) {
        this.phone = phone;
    }

    public String getDepartment() {
        return department;
    }

    public void setDepartment(String department) {
        this.department = department;
    }

    public int getYear() {
        return year;
    }

    public void setYear(int year) {
        this.year = year;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }

    public Timestamp getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Timestamp createdAt) {
        this.createdAt = createdAt;
    }

    public Timestamp getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(Timestamp updatedAt) {
        this.updatedAt = updatedAt;
    }

    @Override
    public String toString() {
        return String.format(
            "Student [ID=%d, Roll=%s, Name=%s, Dept=%s, Year=%d, Email=%s, Phone=%s, Address=%s]",
            id, rollNumber, name, department, year, email, phone, address
        );
    }
}
